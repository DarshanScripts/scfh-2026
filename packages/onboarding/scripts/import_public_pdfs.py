"""Download original municipal PDFs and calculate page-based passages with PDF.js.

Use --from-directory when the originals were downloaded separately. No replacement
PDFs or authored answer snippets are generated by this importer.
"""

import argparse
from hashlib import sha256
import json
from pathlib import Path
import subprocess
import tempfile
from uuid import uuid4
from urllib.error import URLError
from urllib.request import Request, urlopen

from onboarding.contracts import Document, Passage, PdfLocator

PROJECT = Path(__file__).resolve().parents[1]
CATALOG = PROJECT / 'public-corpus' / 'catalog.json'
MAX_BYTES = 40 * 1024 * 1024


def fetch_original(url: str) -> bytes:
    request = Request(url, headers={'User-Agent': 'FacilitiesOnboardingDemo/0.1'})
    with urlopen(request, timeout=60) as response:
        content = response.read(MAX_BYTES + 1)
    if len(content) > MAX_BYTES or not content.startswith(b'%PDF-'):
        raise ValueError('Expected an original PDF under 40 MiB')
    return content


def passages_for_pages(record: dict, document: Document, pages: list[str | dict]) -> list[Passage]:
    if len(pages) != record['expectedPages']:
        raise ValueError(f"Page count changed for {document.documentId}. Review the downloaded source before indexing.")
    texts = [page["text"] if isinstance(page, dict) else page for page in pages]
    if not any('facilit' in page.lower() for page in texts):
        raise ValueError('The source does not appear to be the expected facilities document')
    passages = []
    section = f"PDF page 1"
    for number, page in enumerate(pages, 1):
        text = page["text"] if isinstance(page, dict) else page
        headings = page.get("headings", []) if isinstance(page, dict) else []
        start = 0
        while start < len(text):
            for heading in headings:
                if heading["start"] <= start:
                    section = heading["text"]
            end = min(start + 1000, len(text))
            if end < len(text):
                boundary = text.rfind(' ', start + 650, end)
                if boundary > start:
                    end = boundary
            later_headings = [heading["start"] for heading in headings if start < heading["start"] < end]
            if later_headings:
                end = min(later_headings)
            quote = text[start:end]
            if quote.strip():
                passages.append(Passage(
                    passageId=f'{document.documentId}-p{number}-s{start}',
                    documentId=document.documentId, title=document.title,
                    revision=document.revision,
                    sectionPath=[record['publishedPeriod'], section],
                    quote=quote,
                    locator=PdfLocator(format='pdf', page=number, start=start, end=end),
                ))
            start = end
            while start < len(text) and text[start].isspace():
                start += 1
        if headings:
            section = headings[-1]["text"]
    if not passages:
        raise ValueError('The PDF requires OCR before it can be indexed')
    return passages


def import_corpus(output: Path, from_directory: Path | None, document_ids: list[str] | None = None) -> None:
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    records = catalog["documents"]
    if document_ids:
        known = {record["documentId"] for record in records}
        if not set(document_ids) <= known:
            raise ValueError("Unknown document ID in selection")
        records = [record for record in records if record["documentId"] in document_ids]
    if from_directory and from_directory.resolve() == output.resolve():
        raise ValueError('Use a separate import destination so original input files stay reviewable')
    output.mkdir(parents=True, exist_ok=True)
    # Commit a complete generation only after every original and page index validates.
    with tempfile.TemporaryDirectory(prefix='pdf-import-', dir=output) as staging:
        staged = Path(staging)
        documents = []
        passages = []
        for record in records:
            filename = record['relativePath']
            if Path(filename).name != filename:
                raise ValueError('Invalid catalog filename')
            content = ((from_directory / filename).read_bytes() if from_directory
                       else fetch_original(record['url']))
            if not content.startswith(b'%PDF-') or len(content) > MAX_BYTES:
                raise ValueError(f'Invalid original PDF: {filename}')
            target = staged / filename
            target.write_bytes(content)
            result = subprocess.run(
                ['node', str(PROJECT / 'scripts' / 'pdf-pages.mjs'), str(target), '--layout'],
                check=True, capture_output=True, text=True, timeout=120,
            )
            pages = json.loads(result.stdout)
            document = Document(
                documentId=record['documentId'], title=record['title'], format='pdf',
                revision=sha256(content).hexdigest(), relativePath=filename,
            )
            documents.append(document.model_dump(mode='json'))
            passages.extend(item.model_dump(mode='json') for item in passages_for_pages(record, document, pages))
        index = {'documents': documents, 'passages': passages}
        (staged / 'sources.json').write_text(json.dumps(index, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
        generation = sha256(json.dumps(index, sort_keys=True).encode()).hexdigest()[:16]
        destination = output / generation
        if destination.exists():
            for file in staged.iterdir():
                previous = destination / file.name
                if not previous.is_file() or previous.read_bytes() != file.read_bytes():
                    raise ValueError(f'Existing corpus generation differs at {destination}')
        else:
            staged.rename(destination)
        pointer = output / ('.current-' + uuid4().hex + '.tmp')
        pointer.write_text(generation + '\n', encoding='utf-8')
        pointer.replace(output / 'CURRENT')
        print(f'Imported {len(documents)} original PDFs and {len(passages)} located passages into {destination}')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--from-directory', type=Path)
    parser.add_argument('--output', type=Path, default=PROJECT / 'public-corpus' / 'downloaded')
    parser.add_argument('--document-id', action="append", help="Import only the selected catalog document IDs")
    args = parser.parse_args()
    try:
        import_corpus(args.output, args.from_directory, args.document_id)
    except (OSError, ValueError, URLError, subprocess.SubprocessError) as error:
        parser.exit(1, f'Public PDF import failed. {error}\n')


if __name__ == '__main__':
    main()
