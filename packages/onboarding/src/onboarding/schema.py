"""Export the versioned contracts for browser typing and runtime validation."""

import argparse
import json
from pathlib import Path

from pydantic import TypeAdapter

from .contracts import Answer, CitationRequest, CitationResult, Playback, Request, WalkthroughResult

SCHEMAS = {
    name: TypeAdapter(contract).json_schema()
    for name, contract in {
        "request": Request,
        "answer": Answer,
        "walkthrough": WalkthroughResult,
        "playback": Playback,
        "citationRequest": CitationRequest,
        "citation": CitationResult,
    }.items()
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path("browser/schema.ts")
    content = "// Generated by python -m onboarding.schema.\nexport const schemas = "
    content += json.dumps(SCHEMAS, indent=2, ensure_ascii=False) + " as const;\n"
    if args.check:
        if path.read_text(encoding="utf-8") != content:
            raise SystemExit("Browser contract definitions are out of date")
    else:
        path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
